from django.db import transaction
from rest_framework import serializers
from apps.accounts.serializers import UserSerializer
from apps.accounts.models import User
from .models import Teacher, TeacherDocument, TeacherSalary, SalaryPayment, TeacherAttendance


class TeacherDocumentSerializer(serializers.ModelSerializer):
    uploaded_by_name = serializers.CharField(source='uploaded_by.get_full_name', read_only=True)

    class Meta:
        model = TeacherDocument
        fields = '__all__'
        read_only_fields = ['uploaded_at', 'uploaded_by']


class SalaryPaymentSerializer(serializers.ModelSerializer):
    created_by_name = serializers.CharField(source='created_by.get_full_name', read_only=True)

    class Meta:
        model = SalaryPayment
        fields = '__all__'
        # created_at/created_by are generated by the backend only -- never
        # accepted from the client, and never editable after the fact.
        read_only_fields = ['created_at', 'created_by']

    def validate_amount(self, value):
        if value <= 0:
            raise serializers.ValidationError(
                'Salary payment must be greater than zero.'
            )
        return value

    def validate(self, attrs):
        teacher_salary = attrs.get('teacher_salary') or getattr(self.instance, 'teacher_salary', None)
        amount = attrs.get('amount')

        if teacher_salary and amount is not None:
            already_paid = sum(
                p.amount for p in teacher_salary.payments.exclude(pk=getattr(self.instance, 'pk', None))
            )
            if already_paid + amount > teacher_salary.amount:
                raise serializers.ValidationError(
                    'Payment would exceed the salary amount due for this month.'
                )

        return attrs


class TeacherSalarySerializer(serializers.ModelSerializer):
    teacher_name = serializers.CharField(source='teacher.user.get_full_name', read_only=True)
    employee_id = serializers.CharField(source='teacher.employee_id', read_only=True)
    payments = SalaryPaymentSerializer(many=True, read_only=True)
    paid_amount = serializers.SerializerMethodField()
    remaining_amount = serializers.SerializerMethodField()

    class Meta:
        model = TeacherSalary
        fields = '__all__'
        read_only_fields = ['created_at', 'updated_at', 'created_by']

    def get_paid_amount(self, obj):
        return obj.paid_amount

    def get_remaining_amount(self, obj):
        return obj.remaining_amount

    def validate(self, attrs):
        teacher = attrs.get('teacher') or getattr(self.instance, 'teacher', None)
        month = attrs.get('salary_month') or getattr(self.instance, 'salary_month', None)

        existing = TeacherSalary.objects.filter(teacher=teacher, salary_month=month)
        if self.instance:
            existing = existing.exclude(pk=self.instance.pk)
        if existing.exists():
            raise serializers.ValidationError(
                'A salary record for this teacher and month already exists.'
            )

        return attrs


